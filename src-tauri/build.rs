/// The exact build, for the Settings footer, the window title and device.log (git short hash, commit date, build time).
fn embed_build_info() {
    let git = |args: &[&str]| {
        std::process::Command::new("git")
            .args(args)
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
            .filter(|s| !s.is_empty())
    };
    let mut hash = git(&["rev-parse", "--short=7", "HEAD"]).unwrap_or_else(|| "unknown".into());
    if hash != "unknown"
        && git(&[
            "status",
            "--porcelain",
            "--untracked-files=no",
            "--",
            ":/",
            ":(top,exclude)src-tauri/gen",
            ":(top,exclude)src-tauri/permissions/autogenerated",
        ])
        .is_some()
    {
        hash.push_str("+"); // built with uncommitted changes
    }
    let date = git(&["log", "-1", "--format=%cs"]).unwrap_or_else(|| "unknown".into());
    let built = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    println!("cargo:rustc-env=CS_GIT_HASH={hash}");
    println!("cargo:rustc-env=CS_GIT_DATE={date}");
    println!("cargo:rustc-env=CS_BUILT_AT={built}");
    // rerun (so the time and hash are fresh) when the code, the page or the checked-out commit changes
    for p in ["src", "../public", "../.git/HEAD", "../.git/index"] {
        println!("cargo:rerun-if-changed={p}");
    }
}

